const norm = (s = "") =>
  String(s)
    .replace(/[\u064B-\u0652\u0640]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/[ؤ]/g, "و")
    .replace(/[ئى]/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[^\p{L}\p{N}\s]/gu, "")
    .replace(/\s+/g, " ")
    .replace(/^ال/, "")
    .trim()
    .toLowerCase();

const pickRandom = (list) => list[Math.floor(Math.random() * list.length)];

async function getRiddle() {
  if (RIDDLE_API) {
    try {
      const res = await fetch(RIDDLE_API, { signal: AbortSignal.timeout(8000) });
      let data = await res.json();
      if (Array.isArray(data)) data = pickRandom(data);
      const q = data.question || data.q || data.riddle || data.puzzle || data["لغز"];
      const a = data.answer || data.a || data.solution || data["الجواب"];
      if (q && a) return { q: String(q), a: String(a) };
    } catch {}
  }

  global.riddleBag = global.riddleBag?.length ? global.riddleBag : [...LOCAL];
  const i = Math.floor(Math.random() * global.riddleBag.length);
  return global.riddleBag.splice(i, 1)[0];
}

global.riddleGames ??= {};

function startListener(conn) {
  if (global.riddleListener === conn) return;
  global.riddleListener = conn;

  conn.ev.on("messages.upsert", async ({ messages }) => {
    for (const msg of messages) {
      try {
        if (!msg.message || msg.key.fromMe) continue;

        const chat = msg.key.remoteJid;
        const game = global.riddleGames[chat];
        if (!game) continue;

        const text = (
          msg.message.conversation ||
          msg.message.extendedTextMessage?.text ||
          ""
        ).trim();

        if (!text || /^[.!\/#]/.test(text)) continue;

        const user = msg.key.participant || chat;
        const num = user.split("@")[0].split(":")[0];

        if (game.answers.includes(norm(text))) {
          clearTimeout(game.timer);
          delete global.riddleGames[chat];

          await conn.sendMessage(
            chat,
            {
              text: `✅ إجابة صحيحة يا @${num}!\nالجواب: *${game.a}*`,
              mentions: [user],
            },
            { quoted: msg }
          );
          continue;
        }

        if (text.length > 30 || text.split(/\s+/).length > 4) continue;

        const now = Date.now();
        if (now - (game.last[user] || 0) < WRONG_COOLDOWN) continue;
        game.last[user] = now;

        await conn.sendMessage(
          chat,
          {
            text: `❌ إجابتك خطأ يا @${num} جرب تاني`,
            mentions: [user],
          },
          { quoted: msg }
        );
      } catch {}
    }
  });
}

const handler = async (m, { conn }) => {
  startListener(conn);
  const chat = m.chat;

  if (global.riddleGames[chat])
    return m.reply("فيه لغز شغال الحين، جاوب عليه أول 🧠");

  const r = await getRiddle();
  const answers = r.a.split("|").map((x) => x.trim());

  const timer = setTimeout(async () => {
    if (global.riddleGames[chat]) {
      delete global.riddleGames[chat];
      await m.reply(`⏰ خلص الوقت!\nالجواب: *${answers[0]}*`);
    }
  }, TIMEOUT);

  global.riddleGames[chat] = {
    a: answers[0],
    answers: answers.map(norm),
    timer,
    last: {},
  };

  await m.reply(
    `🧩 *لغز*\n\n${r.q}\n\n⏳ عندك ${TIMEOUT / 1000} ثانية، اكتب الجواب في الشات.`
  );
};

handler.command = ["لغز", "الغاز", "riddle"];
handler.category = "games";
handler.usage = ["لغز"];

export default handler;