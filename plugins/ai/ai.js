const handler = async (m, { conn, text, command }) => {
  const char = characters[command] || Object.values(characters).find(c => c.aliases.includes(command));
  if (!char) return;
  if (!text) return m.reply("💢 ~ حط نص جنب الأمر ~ 🔥");

  const loadingMsg = await conn.sendMessage(m.chat, {
    text: char.loading,
    contextInfo: context(m.sender, char)
  }, { quoted: m });

  const prompt = `
${char.prompt}
و انا اسمي هيكون [ ${m.name || "مز"} ] 
رد علي رسالتي دي:
${text}
`;

  try {
    const union = await (await import("meowsab")).Api.name("union-v");
    const res = await union.url("/ai/chat", { q: prompt });
    
    await conn.sendMessage(m.chat, {
      text: res.response,
      edit: loadingMsg.key,
      contextInfo: context(m.sender, char)
    });
  } catch (e) {
    m.reply("❌ حصل خطأ: " + e.message);
  }
};

const allNames = Object.keys(characters);
const allAliases = Object.values(characters).flatMap(c => c.aliases);

handler.usage = allNames;
handler.category = "ai";
handler.command = [...allNames, ...allAliases];

export default handler;

const context = (jid, char) => ({
  mentionedJid: [jid],
  isForwarded: true,
  forwardingScore: 1,
  forwardedNewsletterMessageInfo: {
    newsletterJid: '@newsletter',
    newsletterName: char.newsletter,
    serverMessageId: 0
  },
  externalAdReply: {
    title: char.title,
    body: char.body,
    thumbnailUrl: char.img,
    sourceUrl: '',
    mediaType: 1,
    renderLargerThumbnail: true
  }
});